// Rule-liveness measurement — regenerates tests/battery/rule-liveness.json.
//
// Purpose: a writing-signal rule that ships in the ACTIVE inventory but cannot
// fire on any real document is a capability the project advertises and does not
// have. This script measures, for every one of the 116 named rules, how many
// documents in the measurement corpora it actually fires on, split by side.
// `rule-liveness-battery.test.mjs` then fails the build if an active rule has a
// zero AI-side fire count and is not recorded as inactive with a reason.
//
// The corpora are NOT in this repository (see docs/programme/HANDOVER.md §2 —
// the programme root is 13 GB and much of the human corpus cannot be
// republished). Two of the four are present in a clone; the other two are read
// from the programme tree when it is available. The committed manifest records
// which corpora were actually measured, with denominators, so a figure is never
// quoted without knowing what it was measured on.
//
// Usage (from the repository root, after `npm run build` in packages/core):
//   node tests/battery/rule-liveness.mjs
//
// Anything that changes the rule inventory must re-run this. The battery test
// fails when the manifest and the built packs disagree, so a new rule cannot be
// added without a measured liveness figure.
import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync, createReadStream } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import readline from "node:readline";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const require = createRequire(import.meta.url);
const D = join(ROOT, "packages", "core", "dist");
const { inspectPatterns } = require(join(D, "patterns", "en-gb-v1.js"));
const { ISSUE_WEIGHTS } = require(join(D, "patterns", "en-signals-v2-data.js"));
const { V3_ISSUE_WEIGHTS } = require(join(D, "patterns", "en-signals-v3-data.js"));
const { V4_ISSUE_WEIGHTS } = require(join(D, "patterns", "en-signals-v4-data.js"));

/** The 3 en-gb-v1 rules, which have their own rule_id namespace. */
export const EN_GB_RULE_IDS = [
  "style.overused_phrase",
  "style.repeated_opening",
  "style.transition_density",
];

/** Every named rule the pack advertises, as the rule_id inspectPatterns emits. */
export function ruleInventory() {
  const categories = [
    ...Object.keys(ISSUE_WEIGHTS),
    ...Object.keys(V3_ISSUE_WEIGHTS),
    ...Object.keys(V4_ISSUE_WEIGHTS),
  ];
  return [...EN_GB_RULE_IDS, ...categories.map((c) => "signals." + c.replace(/-/g, "_"))];
}

const RESEARCH = join(ROOT, "services", "local-engine", "research");

/**
 * Measurement corpora, in the order they are reported. `side` is the
 * authorship side of every document in the corpus; `optional` marks a corpus
 * that lives outside the repository.
 */
const CORPORA = [
  {
    id: "generated-2026-08",
    side: "ai",
    optional: true,
    path: join(RESEARCH, "generated-corpus", "generated.jsonl"),
    note: "4,016 usable current-model long-form articles, 21 models, 10 providers, generated by this project (ours to publish). Published register — the register users actually paste.",
    read: jsonlReader((d) => (d.usable === false ? null : d.text)),
  },
  {
    id: "provider-eval-ai",
    side: "ai",
    optional: true,
    path: join(RESEARCH, "provider-eval", "eval-set.jsonl"),
    note: "The 1,727 AI documents of the 1,896-sample provider-eval set. Chat-reply register, which is why it under-reports rules that measure published-prose cadence.",
    read: jsonlReader((d) => (d.side === "ai" ? d.text : null)),
  },
  {
    id: "provider-eval-human",
    side: "human",
    optional: true,
    path: join(RESEARCH, "provider-eval", "eval-set.jsonl"),
    note: "The 169 held-out human documents of the provider-eval set.",
    read: jsonlReader((d) => (d.side === "ai" ? null : d.text)),
  },
  {
    id: "human-corpus-v2",
    side: "human",
    optional: false,
    path: join(ROOT, "tests", "battery", "human-corpus-v2.json"),
    note: "4,144 modern human samples, 1,233 of them business and marketing copy. Test-only: its manifest forbids training use.",
    read: jsonArrayReader,
  },
  {
    id: "human-corpus-v1",
    side: "human",
    optional: false,
    path: join(ROOT, "tests", "battery", "human-corpus-v1.json"),
    note: "The 40-sample genre-matched verified-human calibration corpus.",
    read: jsonArrayReader,
  },
];

function jsonlReader(pick) {
  return async function* (path) {
    const rl = readline.createInterface({ input: createReadStream(path), crlfDelay: Infinity });
    for await (const line of rl) {
      if (!line.trim()) continue;
      let d;
      try { d = JSON.parse(line); } catch { continue; }
      const text = pick(d);
      if (typeof text === "string" && text.length > 0) yield text;
    }
  };
}

async function* jsonArrayReader(path) {
  const parsed = JSON.parse(readFileSync(path, "utf8"));
  const rows = Array.isArray(parsed) ? parsed : parsed.samples ?? [];
  for (const d of rows) {
    const text = typeof d === "string" ? d : d.text;
    if (typeof text === "string" && text.length > 0) yield text;
  }
}

async function main() {
  const inventory = ruleInventory();
  const counts = Object.fromEntries(inventory.map((r) => [r, {}]));
  const corpora = [];

  for (const c of CORPORA) {
    if (!existsSync(c.path)) {
      if (!c.optional) throw new Error(`missing required corpus: ${c.path}`);
      corpora.push({ id: c.id, side: c.side, documents: null, skipped: "corpus not present in this checkout", note: c.note });
      process.stderr.write(`skip ${c.id} (not present)\n`);
      continue;
    }
    let n = 0;
    for await (const text of c.read(c.path)) {
      n += 1;
      const fired = new Set(inspectPatterns(text).map((f) => f.rule_id));
      for (const r of fired) {
        if (counts[r] === undefined) continue; // unknown id: reported below
        counts[r][c.id] = (counts[r][c.id] ?? 0) + 1;
      }
      if (n % 500 === 0) process.stderr.write(`${c.id}: ${n}\n`);
    }
    corpora.push({ id: c.id, side: c.side, documents: n, note: c.note });
    process.stderr.write(`${c.id}: ${n} documents\n`);
  }

  const aiIds = corpora.filter((c) => c.side === "ai" && c.documents).map((c) => c.id);
  const humanIds = corpora.filter((c) => c.side === "human" && c.documents).map((c) => c.id);
  const sum = (rule, ids) => ids.reduce((a, id) => a + (counts[rule][id] ?? 0), 0);

  const rules = {};
  for (const r of inventory) {
    rules[r] = {
      ai_documents_fired: sum(r, aiIds),
      human_documents_fired: sum(r, humanIds),
      by_corpus: counts[r],
    };
  }

  const manifest = {
    generated_by: "tests/battery/rule-liveness.mjs",
    measured_utc: new Date().toISOString().slice(0, 10),
    engine_version: require(join(D, "patterns", "en-signals-v2.js")).EN_SIGNALS_PATTERN_VERSION,
    named_rules: inventory.length,
    denominators: {
      ai_documents: corpora.filter((c) => c.side === "ai").reduce((a, c) => a + (c.documents ?? 0), 0),
      human_documents: corpora.filter((c) => c.side === "human").reduce((a, c) => a + (c.documents ?? 0), 0),
    },
    corpora,
    // Rules that measure zero AI-side fires and are knowingly shipped anyway.
    // Every entry needs a reason. The battery test fails on any zero-fire rule
    // that is not listed here, and on any listed rule that has started firing.
    inactive: JSON.parse(readFileSync(join(HERE, "rule-liveness-inactive.json"), "utf8")),
    rules,
  };
  writeFileSync(join(HERE, "rule-liveness.json"), JSON.stringify(manifest, null, 1) + "\n");

  const dead = inventory.filter((r) => rules[r].ai_documents_fired === 0);
  process.stderr.write(`\n${inventory.length} named rules; ${dead.length} with zero AI-side fires:\n`);
  for (const r of dead) process.stderr.write(`  ${r} (human ${rules[r].human_documents_fired})\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  await main();
}
