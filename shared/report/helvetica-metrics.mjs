/** Width of one already-WinAnsi-encoded string, in PDF points. */
export function measureWinAnsi(text, weight, size) {
  const widths = WIDTH_TABLES[weight] ?? HELVETICA_WIDTHS;
  let total = 0;
  const value = String(text ?? '');
  for (let index = 0; index < value.length; index += 1) {
    total += widths[value.charCodeAt(index) & 0xff] || 0;
  }
  return (total * size) / 1000;
}
