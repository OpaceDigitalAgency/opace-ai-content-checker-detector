const LOOKUP = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

/** Decode base64 to bytes without atob or Buffer, so the module runs anywhere. */
export function decodeBase64(value) {
  const clean = String(value).replace(/[^A-Za-z0-9+/]/gu, '');
  const bytes = new Uint8Array(Math.floor((clean.length * 3) / 4));
  let cursor = 0;
  let buffer = 0;
  let bits = 0;
  for (const character of clean) {
    buffer = (buffer << 6) | LOOKUP.indexOf(character);
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      bytes[cursor] = (buffer >> bits) & 0xff;
      cursor += 1;
    }
  }
  return bytes.subarray(0, cursor);
}

/** The PDF header logo as JPEG bytes. */
export const logoJpegBytes = () => decodeBase64(LOGO_JPEG_128_BASE64);
